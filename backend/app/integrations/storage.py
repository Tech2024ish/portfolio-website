"""Object storage for the media library.

- ``supabase``: Supabase Storage through its HTTP API, authenticated with the service key,
  which never leaves the backend. The bucket must allow public reads; writes and deletes are
  possible only with that key, so only this API can change it.
- ``local``: files under ``LOCAL_MEDIA_DIR``, served by the API itself. Development only
  (refused in production: Render's disk is not durable).
- ``disabled``: no storage; the media endpoints answer 503.

Keys are generated by the API only (``{folder}/{uid}/r{revision}/{name}``) and never come from
a client, so they cannot escape the bucket or the media directory.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Protocol

import httpx

from app.core.config import Settings, StorageBackend
from app.core.errors import AppError

LOCAL_FILES_PATH = "/api/v1/media/files"
KEY_PATTERN = re.compile(
    r"^(profile|projects|notes|general)/[0-9a-f]{32}/r[0-9]{1,6}/(original\.(jpg|png|webp)|w[0-9]{2,4}\.webp)$"
)
# Every stored object gets a new key when it changes, so it can be cached forever.
IMMUTABLE = "public, max-age=31536000, immutable"


class StorageError(Exception):
    pass


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...

    def delete(self, keys: list[str]) -> None: ...

    def url(self, key: str) -> str: ...


def _checked(key: str) -> str:
    if not KEY_PATTERN.match(key):
        raise StorageError("invalid storage key")
    return key


class LocalStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def path(self, key: str) -> Path:
        path = (self.root / _checked(key)).resolve()
        if not path.is_relative_to(self.root):  # defence in depth; the pattern already prevents it
            raise StorageError("invalid storage key")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self.path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def delete(self, keys: list[str]) -> None:
        for key in keys:
            self.path(key).unlink(missing_ok=True)

    def url(self, key: str) -> str:
        return f"{LOCAL_FILES_PATH}/{_checked(key)}"


class SupabaseStorage:
    def __init__(
        self, base_url: str, service_key: str, bucket: str, client: httpx.Client | None = None
    ) -> None:
        self.base = base_url.rstrip("/")
        self.bucket = bucket
        self.client = client or httpx.Client(timeout=30.0)
        self.headers = {"Authorization": f"Bearer {service_key}", "apikey": service_key}

    def put(self, key: str, data: bytes, content_type: str) -> None:
        response = self.client.post(
            f"{self.base}/storage/v1/object/{self.bucket}/{_checked(key)}",
            content=data,
            headers={
                **self.headers,
                "Content-Type": content_type,
                "Cache-Control": "max-age=31536000",
                "x-upsert": "false",
            },
        )
        if response.status_code not in (200, 201):
            # The status only: response bodies may echo request details.
            raise StorageError(f"upload failed with status {response.status_code}")

    def delete(self, keys: list[str]) -> None:
        if not keys:
            return
        response = self.client.request(
            "DELETE",
            f"{self.base}/storage/v1/object/{self.bucket}",
            json={"prefixes": [_checked(key) for key in keys]},
            headers=self.headers,
        )
        if response.status_code not in (200, 204):
            raise StorageError(f"delete failed with status {response.status_code}")

    def url(self, key: str) -> str:
        return f"{self.base}/storage/v1/object/public/{self.bucket}/{_checked(key)}"


def storage_for(settings: Settings) -> Storage:
    """The configured storage, or a 503 when media storage is not set up."""
    if settings.storage_backend is StorageBackend.LOCAL:
        return LocalStorage(Path(settings.local_media_dir))
    if (
        settings.storage_backend is StorageBackend.SUPABASE
        and settings.supabase_url
        and settings.supabase_service_key
    ):
        return SupabaseStorage(
            settings.supabase_url,
            settings.supabase_service_key.get_secret_value(),
            settings.media_bucket,
        )
    raise AppError(503, "storage_unavailable", "Media storage is not configured on the server.")

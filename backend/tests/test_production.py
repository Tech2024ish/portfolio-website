def test_legacy_contacts_import_dry_run_then_apply_then_nothing_twice(
    make_auth_settings: Callable[..., Settings],
    legacy: str,
    query: Query,
    capsys: pytest.CaptureFixture[str],
) -> None:
    settings = make_auth_settings()
    code, out = run(settings, "import-legacy-contacts", capsys=capsys)
    assert code == 0
    assert "2 message(s) to import, 0 already imported, 1 skipped as invalid" in out
    assert "Dry run" in out
    assert query("select count(*) from contact_messages") == [(0,)]

    code, out = run(settings, "import-legacy-contacts", "--apply", capsys=capsys)
    assert code == 0 and "Imported 2 message(s). No email was sent." in out
    rows = query(
        "select name, subject, status, created_at::date::text "
        "from contact_messages order by created_at"
    )
    assert rows == [
        ("Ada Lovelace", "Message from the previous website", "new", "2026-05-01"),
        ("Grace Hopper", "Message from the previous website", "new", "2026-06-02"),
    ]
    assert query("select count(*) from email_deliveries") == [(0,)]
    assert query("select count(*) from legacy.contacts") == [(3,)]  # untouched

    _, out = run(settings, "import-legacy-contacts", "--apply", capsys=capsys)
    assert "0 message(s) to import, 2 already imported" in out
    assert query("select count(*) from contact_messages") == [(2,)]


def test_the_client_address_diagnostics_are_owner_only(
    make_api: Callable[..., TestClient], owner: int
) -> None:
    client = make_api(trusted_proxy_count=2)
    assert client.get("/api/v1/owner/diagnostics/client-address").status_code == 401
    signed_in(client)
    body = client.get(
        "/api/v1/owner/diagnostics/client-address",
        headers={"X-Forwarded-For": "198.51.100.7, 203.0.113.9"},
    ).json()
    assert body["x_forwarded_for"] == ["198.51.100.7", "203.0.113.9"]
    assert body["resolved"] == "198.51.100.7"
    assert body["candidates"]["1"] == "203.0.113.9"
    assert body["candidates"]["2"] == "198.51.100.7"


def test_every_response_carries_a_request_id(make_api: Callable[..., TestClient]) -> None:
    client = make_api()
    first = client.get("/health").headers["x-request-id"]
    assert len(first) == 32 and first != client.get("/health").headers["x-request-id"]
    kept = client.get("/health", headers={"X-Request-ID": "trace-12345678"})
    assert kept.headers["x-request-id"] == "trace-12345678"
    injected = client.get("/health", headers={"X-Request-ID": "bad id\nwith newline"})
    assert injected.headers["x-request-id"] != "bad id\nwith newline"
    assert client.get("/api/v1/owner/settings").headers["x-request-id"]  # errors too

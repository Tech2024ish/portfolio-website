"""Migration history must match the models and must never target legacy tables."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text

BACKEND = Path(__file__).resolve().parents[1]

LEGACY_DDL = [
    "CREATE TABLE projects (id INTEGER PRIMARY KEY, title TEXT NOT NULL, description TEXT NOT NULL)",
    "CREATE TABLE skills (id INTEGER PRIMARY KEY, name TEXT NOT NULL, category TEXT NOT NULL, level INTEGER)",
    "CREATE TABLE contacts (id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL, message TEXT NOT NULL,"
    " created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)",
    "CREATE TABLE visit_stats (id INTEGER PRIMARY KEY, count INTEGER NOT NULL DEFAULT 0)",
]


def alembic_config(url: str) -> Config:
    cfg = Config(str(BACKEND / "alembic.ini"))
    cfg.set_main_option("script_location", str(BACKEND / "alembic"))
    cfg.attributes["url"] = url
    return cfg


@pytest.fixture
def legacy_db(tmp_path):
    url = f"sqlite:///{(tmp_path / 'legacy.db').as_posix()}"
    engine = create_engine(url)
    with engine.begin() as conn:
        for ddl in LEGACY_DDL:
            conn.execute(text(ddl))
        conn.execute(text("INSERT INTO visit_stats (id, count) VALUES (1, 42)"))
    yield url, engine
    engine.dispose()


def test_check_ignores_legacy_tables_and_reports_no_drift(legacy_db):
    url, _ = legacy_db
    cfg = alembic_config(url)
    command.upgrade(cfg, "head")
    # Raises AutogenerateDiffsDetected if models and migrations disagree, or if
    # autogenerate would propose touching the legacy tables.
    command.check(cfg)


def test_check_still_detects_real_model_drift(legacy_db):
    """The filter must not hide genuine differences in managed tables."""
    url, engine = legacy_db
    cfg = alembic_config(url)
    command.upgrade(cfg, "head")
    with engine.begin() as conn:
        conn.execute(text("DROP INDEX ix_activity_log_created_at"))
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(cfg)


def test_upgrade_and_downgrade_preserve_legacy_tables(legacy_db):
    url, engine = legacy_db
    cfg = alembic_config(url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
    tables = set(inspect(engine).get_table_names())
    assert {"projects", "skills", "contacts", "visit_stats"} <= tables
    with engine.connect() as conn:
        assert conn.execute(text("SELECT count FROM visit_stats WHERE id = 1")).scalar() == 42


def test_legacy_table_list_matches_supabase_schema():
    source = (BACKEND / "alembic" / "env.py").read_text(encoding="utf-8")
    schema = (BACKEND.parent / "supabase_schema.sql").read_text(encoding="utf-8")
    for table in ("projects", "skills", "contacts", "visit_stats"):
        assert f"CREATE TABLE {table}" in schema
        assert f'"{table}"' in source
